 perform delete_records('expense',array[eid],true,'delete expense',actor_id);
 if exists(select 1 from expenses where id=eid and not voided and deleted_at is null) then raise exception 'Deleted expense counted';end if;
 perform delete_records('expense',array[eid],false,'restore expense',actor_id);
 if not exists(select 1 from audit where details->'before'->>'id'=eid::text and action like 'ลบ %') then raise exception 'Deletion audit missing';end if;
 if has_function_privilege('anon','public.delete_records(text,uuid[],boolean,text,uuid)','execute') or has_function_privilege('authenticated','public.update_own_profile(uuid,text,text,text,text)','execute') then raise exception 'Private RPC grants unsafe';end if;
 perform update_own_profile(member_id,'test edited name','2','0123456789','test@example.invalid');
 if not exists(select 1 from profiles where id=member_id and phone='0123456789' and year='2' and role='member') then raise exception 'Self profile update failed';end if;
end $$;
rollback;
select 'passed: delete/restore financial totals, retained evidence, pending uniqueness, parent deletion, user access, self protection, audit, profile update and grants; all test changes rolled back' as result;
