const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict'),{JSDOM}=require('jsdom');
const root=require('node:path').resolve(__dirname,'..');
(async()=>{
const dom=new JSDOM('<div id="app"><div class="layout"><div class="mobile-scrim"></div><aside class="sidebar"><nav class="nav"></nav></aside><div class="workspace"><header class="topbar"><button class="topbar-back">back</button><div class="user"></div></header><main></main></div><nav class="clay-dock" aria-label="เมนูด่วน"><button data-view="dashboard"><svg></svg><span>หน้าหลัก</span></button><button data-view="bills"><svg></svg><span>บิล</span></button><button data-view="history"><svg></svg><span>ประวัติ</span></button><button data-view="fund"><svg></svg><span>การเงิน</span></button><button data-action="menu"><svg></svg><span>เมนู</span></button></nav></div></div>',{url:'https://example.test',runScripts:'outside-only',pretendToBeVisual:true});
const w=dom.window,ctx=dom.getInternalVMContext(),layout=w.document.querySelector('.layout');
let y=0;
Object.defineProperty(w,'scrollY',{configurable:true,get:()=>y});
w.matchMedia=()=>({matches:true,media:'(max-width:720px)'});
w.user={id:'member-1',role:'member'};w.view='dashboard';w.db={notifications:[]};w.cfg={mode:'demo'};
w.shopLoaded=true;w.shopOwner='member-1';w.shopData={products:[{id:'for-sale'}]};w.shopSaleState=()=> 'open';
w.icon=()=>'<svg></svg>';w.esc=x=>String(x);w.noticeRow=()=>'';w.render=()=>{};w.api=async()=>({});
w.document.scrollingElement.scrollTop=0;
const setScroll=value=>{y=value;w.document.scrollingElement.scrollTop=value;w.dispatchEvent(new w.Event('scroll'));};
vm.runInContext(fs.readFileSync(root+'/web/shop-notice-navigation.js','utf8'),ctx);
const dock=w.document.querySelector('.clay-dock');
assert.ok(dock.querySelector('.mobile-dock-store-entry'),'store appears inside the mobile bottom dock');
assert.equal(dock.style.getPropertyValue('--mobile-dock-compact-width'),'314px','compact width is calculated for all six dock buttons including the store');
assert.equal(w.document.querySelector('#app > .mobile-store-entry'),null,'no separate floating store button remains');
assert.equal(layout.classList.contains('mobile-header-hidden'),false,'header starts visible');
setScroll(90);
assert.ok(layout.classList.contains('mobile-page-scrolled'),'scrolling down marks the page as scrolled');
assert.ok(layout.classList.contains('mobile-header-hidden'),'header slides away while scrolling down');
setScroll(66);
assert.ok(!layout.classList.contains('mobile-header-hidden'),'header slides back while scrolling up');
setScroll(92);
assert.ok(layout.classList.contains('mobile-header-hidden'),'header hides again on the next downward scroll');
assert.ok(layout.classList.contains('mobile-page-scrolled'),'dock folds while scrolling down');
setScroll(80);
assert.ok(!layout.classList.contains('mobile-header-hidden'),'header returns while scrolling up before reaching the top');
assert.ok(!layout.classList.contains('mobile-page-scrolled'),'dock expands while scrolling up before reaching the top');
setScroll(0);
assert.ok(!layout.classList.contains('mobile-header-hidden'),'header is always visible at the top');
assert.ok(!layout.classList.contains('mobile-page-scrolled'),'dock returns to its expanded state at the top');
w.view='shop';w.render();
assert.equal(dock.querySelector('.mobile-dock-store-entry'),null,'store is not duplicated while already on the shop page');
assert.ok(layout.classList.contains('mobile-dock-hidden'),'main dock keeps its existing hide-on-shop-page behavior');
assert.equal(dock.style.getPropertyValue('--mobile-dock-compact-width'),'264px','compact width updates when the store button is removed from the dock');
w.view='dashboard';w.user.role='admin';w.render();
assert.ok(dock.querySelector('.mobile-dock-store-entry'),'admin also gets the store inside the dock when sale items exist');
assert.equal(dock.style.getPropertyValue('--mobile-dock-compact-width'),'314px','compact width expands to fit the store button without a jump');
assert.ok(w.document.querySelector('.mobile-topbar-menu'),'admin mobile menu remains available in the header');
setScroll(90);
assert.ok(layout.classList.contains('mobile-page-scrolled'),'dock is compact before changing page');
w.view='members';w.render();
assert.ok(layout.classList.contains('mobile-page-scrolled'),'new page starts from the compact dock state for its expansion transition');
await new Promise(resolve=>w.requestAnimationFrame(resolve));
assert.ok(!layout.classList.contains('mobile-page-scrolled'),'dock expands after a menu navigation frame');
const css=fs.readFileSync(root+'/web/shop-notice-navigation.css','utf8');
assert.match(css,/mobile-header-hidden[^}]*topbar/s,'mobile header has an animated hidden state');
assert.match(css,/mobile-page-scrolled \.clay-dock[\s\S]*?left:50%[\s\S]*?translate3d\(-50%,0,0\)/,'scrolled dock folds into the center');
assert.match(css,/mobile-dock-store-entry/,'the store button has compact-dock styles');
assert.match(css,/mobile-page-scrolled \\.clay-dock > button > span[\\s\\S]*?visibility:hidden/s,'all labels including the store label disappear when the dock is folded');
assert.match(css,/transition:transform \\.58s cubic-bezier/,'mobile header slide animation is slower');
assert.match(css,/transform \\.58s cubic-bezier/,'mobile dock fold animation is slower');
const stableDock=css.slice(css.lastIndexOf('/* Stable, non-bouncing mobile dock collapse.'));
assert.ok(stableDock.includes('width:calc(100vw - 24px)'),'expanded dock has an explicit interpolable width');
assert.ok(stableDock.includes('width:var(--mobile-dock-compact-width'),'compact dock uses a measured numeric target width');
assert.ok(stableDock.includes('transform:translate3d(-50%,0,0)'),'dock stays centered without scale bounce');
assert.ok(!stableDock.includes('width:max-content')&&!stableDock.includes('scale(.96)')&&!stableDock.includes('flex-grow'),'compact dock has no intrinsic-width jump, scale bounce, or flex-grow rebound');
console.log('Mobile header direction, upward dock expansion, route-change animation, and store behavior passed');
w.close();
})().catch(error=>{console.error(error);process.exitCode=1});
