const fs=require('node:fs');
const assert=require('node:assert/strict');
const {JSDOM}=require('jsdom');
const root=require('node:path').resolve(__dirname,'..');
const dom=new JSDOM('<div id="app"></div><dialog id="dialog"></dialog><div id="toast"></div>',{url:'https://example.test',runScripts:'outside-only'});
const w=dom.window;
w.FINANCE_CONFIG={mode:'demo',bankName:'พร้อมเพย์',accountName:'ทดสอบ',accountNumber:'001',paymentQrUrl:'./payment-qr.png',lineOaUrl:'https://lin.ee/test'};
w.HTMLDialogElement.prototype.showModal=function(){this.open=true};
w.HTMLDialogElement.prototype.close=function(){this.open=false};
const context=dom.getInternalVMContext(),vm=require('node:vm');
for(const file of ['app.js','management.js','records.js','bills.js','account-access.js','batch-registration.js']){
 vm.runInContext(fs.readFileSync(root+'/web/'+file,'utf8'),context,{filename:file});
}
const run=source=>vm.runInContext(source,context);
let copied='';
Object.defineProperty(w.navigator,'clipboard',{configurable:true,value:{writeText:async value=>{copied=value}}});
const tick=()=>new Promise(resolve=>setImmediate(resolve));
(async()=>{
 run("demoLogin('admin')");
 await run('registrationList()');
 const add=w.document.querySelector('[data-prepare-members]');
 assert.ok(add,'signup history offers adding prepared members');
 add.click();
 const form=w.document.querySelector('#prepare-members-form');
 assert.ok(form,'prepared member form opens');
 form.querySelector('[name=student_id]').value='67019998';
 form.querySelector('[name=name_prefix]').value='นาย';
 form.querySelector('[name=first_name]').value='ทดสอบ';
 form.querySelector('[name=last_name]').value='ลิงก์สมัคร';
 form.querySelector('[name=year]').value='1';
 form.requestSubmit();
 await tick();
 assert.equal(run("demoInvites.find(row=>row.student_id==='67019998').status"),'draft');
 const checkbox=w.document.querySelector('#registration-batch-form [name=invite_ids]');
 assert.ok(checkbox,'member without a link can be selected');
 checkbox.checked=true;
 w.document.querySelector('#registration-batch-form').requestSubmit();
 await tick();
 assert.ok(w.document.querySelector('#generated-invite-url'),'new link is displayed after creation');
 await run('registrationList()');
 const copy=w.document.querySelector('[data-copy-registration-link]');
 assert.ok(copy,'saved link is listed for reuse');
 const card=copy.closest('.registration-link-card');
 assert.match(card.textContent,/ทดสอบ ลิงก์สมัคร/,'history shows who the link was created for');
 assert.match(card.textContent,/67019998/,'history shows the student ID');
 const cancelId=card.querySelector('[data-cancel-registration-batch]').dataset.cancelRegistrationBatch;
 copy.click();
 await tick();
 assert.match(copied,/#token=demo-/,'copy button reuses the saved URL');
 card.querySelector('[data-cancel-registration-batch]').click();
 const confirm=w.document.querySelector('[data-confirm-cancel-registration-batch]');
 assert.ok(confirm,'cancellation requires confirmation');
 assert.equal(confirm.dataset.confirmCancelRegistrationBatch,cancelId);
 confirm.click();
 await tick();
 assert.match(w.document.querySelector('#dialog').textContent,/ยกเลิกแล้ว/,'cancelled batch remains visible in history');
 assert.equal(w.document.querySelector('[data-copy-registration-link]'),null,'cancelled link is no longer offered for copying');
 console.log('Signup link history, saved URL copy, member identity display and batch cancellation passed');
 w.close();
})().catch(error=>{console.error(error);process.exitCode=1;w.close()});
